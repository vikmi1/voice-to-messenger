package com.voicetomessenger.ui

import androidx.compose.ui.graphics.Color

/**
 * Общая палитра игр — тёплые тона оригинального 2048.
 *
 * Цвета фиксированы и одинаковы в светлой и тёмной теме: игровые экраны самодостаточны,
 * плитки читаются привычно, а новые игры выглядят в едином стиле.
 */
object GamePalette {
    /** Фон доски. */
    val Board = Color(0xFFBBADA0)

    /** Пустая клетка / непройденная ячейка. */
    val EmptyCell = Color(0xFFCDC1B4)

    /** Светлая ячейка (числа Шульте, младшие плитки 2048). */
    val LightCell = Color(0xFFEEE4DA)

    /** Тёмный текст на светлых ячейках. */
    val TextDark = Color(0xFF776E65)

    /** Светлый текст на насыщенных ячейках. */
    val TextLight = Color(0xFFF9F6F2)

    /**
     * Короткая зелёная вспышка на верном нажатии. Именно вспышка, а не заливка:
     * закрашенные ячейки Шульте подсказывали бы, какие числа ещё не найдены.
     */
    val Correct = Color(0xFF3E9B4F)

    /** Короткая вспышка на неверном клике. */
    val Wrong = Color(0xFFF65E3B)

    /** Лучшая попытка на графике прогресса — золотая, как плитка 2048. */
    val Best = Color(0xFFEDC22E)

    /** Акцент: следующее число, активный размер таблицы. */
    val Accent = Color(0xFFF2B179)
}
