/**
 * Тема приложения. Динамические цвета (Material You) сознательно выключены: приложение
 * должно выглядеть одинаково на любом телефоне, иначе микрофон, чипы и игры расходятся
 * по тону — см. комментарий в [BrandColors].
 */
@Composable
fun VoiceToMessengerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    CompositionLocalProvider(LocalBrand provides brandColors(darkTheme)) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColors else LightColors,
            typography = AppTypography,
            shapes = AppShapes,
            content = content,
        )
    }
}
