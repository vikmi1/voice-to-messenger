"""Построение системного промпта для обработки текста.

Главная задача — заставить модель вернуть ТОЛЬКО готовый текст сообщения,
без служебных обёрток вроде «вот ваш текст». Это ключевая фишка продукта.
"""

DEFAULT_BASE_PROMPT = (
    "Ты — редактор коротких сообщений для мессенджеров. Пользователь надиктовал текст голосом, "
    "поэтому на входе — живая разговорная речь со словами-паразитами, повторами, "
    "самоперебивками и оговорками. Это нормально и ожидаемо.\n"
    "\n"
    "Твоя задача — ВСЕГДА превратить эту речь в чистое, готовое к отправке сообщение:\n"
    "- убери слова-паразиты («ну», «это самое», «короче», «типа», «как бы»), повторы и оговорки;\n"
    "- исправь грамматику, орфографию и пунктуацию;\n"
    "- сделай текст связным и естественным, сохранив смысл и намерение;\n"
    "- сохрани все факты, числа, имена, даты, ссылки и просьбы; ничего не выдумывай и не "
    "добавляй от себя;\n"
    "- сохрани исходный язык сообщения, если не задан перевод.\n"
    "\n"
    "Пример:\n"
    "Вход: «ну это самое короче слушай надо бы завтра встретиться где-то часа в три ну или в "
    "четыре обсудить вопрос по проекту»\n"
    "Выход: «Слушай, надо бы завтра встретиться часа в три-четыре, обсудить вопрос по проекту.»\n"
    "\n"
    "ЗАПРЕЩЕНО: отвечать, что не можешь разобрать текст; просить повторить или надиктовать "
    "заново; извиняться; добавлять любые комментарии. Даже если речь сбивчивая — всё равно "
    "составь из неё осмысленное сообщение.\n"
    "\n"
    "ОЧЕНЬ ВАЖНО: верни ТОЛЬКО итоговый текст сообщения — без вступлений, пояснений, кавычек "
    "и Markdown. Только сам текст."
)


def build_system(
    base_prompt: str,
    style_prompt: str,
    target_lang: str,
    target_lang_name: str,
    examples: list[str] | None = None,
    emoji: bool = False,
    as_list: bool = False,
) -> str:
    """Собирает системный промпт из базового, стиля, примеров и (опционально) перевода.

    examples — сообщения самого пользователя для стиля «Мой стиль»: модель подражает
    их тону. emoji/as_list — переключатели «расставь эмодзи» и «оформи списком».
    """
    parts = [(base_prompt or DEFAULT_BASE_PROMPT).strip()]

    if style_prompt and style_prompt.strip():
        parts.append("Тон и стиль: " + style_prompt.strip())

    sample = "\n".join(f"— {e.strip()}" for e in (examples or []) if e and e.strip())
    if sample:
        parts.append(
            "Ниже — примеры сообщений самого пользователя. Подражай их тону, манере, "
            "типичной длине и выбору слов, но пиши строго по смыслу текущей надиктовки и "
            "ничего из примеров не копируй дословно:\n" + sample
        )

    if emoji:
        parts.append(
            "Расставь уместные эмодзи по смыслу — умеренно, только там, где это естественно "
            "усиливает сообщение. Не лепи эмодзи в каждую строку и не начинай ими сообщение."
        )

    if as_list:
        parts.append(
            "Оформи результат как список: каждый пункт с новой строки, в начале строки — «☐ » "
            "(символ пустого чекбокса и пробел). Без нумерации, без вступления и заключения — "
            "только сами пункты по сути надиктовки."
        )

    if target_lang and target_lang != "off":
        name = target_lang_name or target_lang
        parts.append(
            f"Переведи итоговое сообщение на язык: {name}. "
            f"Верни только перевод, без оригинала и без пометок."
        )

    return "\n\n".join(parts)
