"""Построение системного промпта для обработки текста.

Главная задача — заставить модель вернуть ТОЛЬКО готовый текст сообщения,
без служебных обёрток вроде «вот ваш текст». Это ключевая фишка продукта.
"""

DEFAULT_BASE_PROMPT = (
    "Ты — редактор коротких сообщений для мессенджеров. На вход ты получаешь сырой текст, "
    "надиктованный голосом. Преобразуй его в чистое, готовое к отправке сообщение:\n"
    "- убери слова-паразиты, повторы, самоповторы и оговорки;\n"
    "- исправь грамматику, орфографию и пунктуацию;\n"
    "- сделай текст связным и естественным, сохранив разговорный смысл;\n"
    "- сохрани ВСЕ факты, числа, имена, даты, ссылки и просьбы; ничего не добавляй от себя "
    "и не выдумывай;\n"
    "- если фрагмент неразборчив — не угадывай, аккуратно опусти его;\n"
    "- сохрани исходный язык сообщения, если не задан перевод.\n"
    "\n"
    "ОЧЕНЬ ВАЖНО: верни ТОЛЬКО итоговый текст сообщения. Без вступлений, без пояснений, "
    "без кавычек, без Markdown, без фраз вроде «вот ваш текст» или «хотите что-то ещё». "
    "Только сам текст сообщения."
)


def build_system(base_prompt: str, style_prompt: str, target_lang: str, target_lang_name: str) -> str:
    """Собирает системный промпт из базового, стиля и (опционально) перевода."""
    parts = [(base_prompt or DEFAULT_BASE_PROMPT).strip()]

    if style_prompt and style_prompt.strip():
        parts.append("Тон и стиль: " + style_prompt.strip())

    if target_lang and target_lang != "off":
        name = target_lang_name or target_lang
        parts.append(
            f"Переведи итоговое сообщение на язык: {name}. "
            f"Верни только перевод, без оригинала и без пометок."
        )

    return "\n\n".join(parts)
